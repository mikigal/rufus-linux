#!/usr/bin/env python3
#
# Generate src/core/windows_zones.h, the Windows names of the IANA time zones,
# from the windowsZones.xml and bcp47/timezone.xml files of Unicode CLDR.
#
# Usage: res/linux/windows_zones.py [<CLDR common directory>] > src/core/windows_zones.h
# Without a directory, the files are downloaded from the main branch of CLDR.

import sys
import urllib.request
import xml.etree.ElementTree as ET

CLDR_URL = "https://raw.githubusercontent.com/unicode-org/cldr/main/common/"


def read(path):
    if len(sys.argv) > 1:
        with open(f"{sys.argv[1]}/{path}", "rb") as f:
            return f.read()
    with urllib.request.urlopen(CLDR_URL + path) as r:
        return r.read()


zones = {}
for m in ET.fromstring(read("supplemental/windowsZones.xml")).iter("mapZone"):
    for iana in m.get("type").split():
        # The "001" (world) mapping comes first, and is the one to use
        zones.setdefault(iana, m.get("other"))

# Every alias of a zone (Asia/Calcutta is Asia/Kolkata, Europe/Kiev is Europe/Kyiv...)
for t in ET.fromstring(read("bcp47/timezone.xml")).iter("type"):
    aliases = (t.get("alias") or "").split()
    known = [a for a in aliases if a in zones]
    if known:
        for a in aliases:
            zones.setdefault(a, zones[known[0]])

print("// Autogenerated by res/linux/windows_zones.py from Unicode CLDR - DO NOT EDIT")
print()
print("#pragma once")
print()
print("// The Windows names of the IANA time zones, sorted by IANA name")
print("static const struct { const char* iana; const char* windows; } windows_zones[] = {")
for iana in sorted(zones):
    print(f'\t{{ "{iana}", "{zones[iana]}" }},')
print("};")
